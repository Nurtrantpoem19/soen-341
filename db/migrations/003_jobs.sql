CREATE TABLE IF NOT EXISTS jobs (
    id SERIAL PRIMARY KEY,
    recruiter_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    title TEXT NOT NULL CHECK (length(trim(title)) BETWEEN 1 AND 200),
    company TEXT NOT NULL CHECK (length(trim(company)) BETWEEN 1 AND 200),
    location TEXT NOT NULL CHECK (length(trim(location)) BETWEEN 1 AND 200),
    category TEXT NOT NULL CHECK (length(trim(category)) BETWEEN 1 AND 100),
    employment_type TEXT NOT NULL CHECK (employment_type IN ('Full-time', 'Part-time', 'Internship', 'Contract')),
    salary TEXT NOT NULL DEFAULT '' CHECK (length(salary) <= 100),
    description TEXT NOT NULL CHECK (length(trim(description)) BETWEEN 1 AND 5000),
    requirements TEXT NOT NULL DEFAULT '' CHECK (length(requirements) <= 5000),
    is_open BOOLEAN NOT NULL DEFAULT TRUE,
    posted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS jobs_category_idx ON jobs(category);
CREATE INDEX IF NOT EXISTS jobs_posted_at_idx ON jobs(posted_at);
